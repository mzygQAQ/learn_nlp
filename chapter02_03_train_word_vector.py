from gensim.models import Word2Vec, KeyedVectors
from gensim.test.utils import common_texts

# 语料按语义分组刻意构造：同一组的词共享相近的上下文（水果都与"吃/买/甜"共现，
# 动物都与"可爱/宠物/吃"共现，电脑硬件都与"程序/数据"共现），
# 这样 skip-gram 才有机会把它们学成相近的向量，而不是一团随机噪声。
TEST_SENTENCES = [
    # ---- 水果 ----
    ['我', '喜欢', '吃', '苹果'],
    ['我', '喜欢', '吃', '香蕉'],
    ['苹果', '和', '香蕉', '都', '是', '水果'],
    ['西瓜', '在', '夏天', '最', '受欢迎'],
    ['草莓', '很', '甜', '葡萄', '很', '酸'],
    ['我', '买', '了', '苹果', '和', '橘子'],
    ['妈妈', '买', '了', '西瓜', '和', '葡萄'],
    ['新鲜', '的', '水果', '吃', '起来', '很', '健康'],
    # ---- 动物 ----
    ['我', '的', '猫', '很', '可爱'],
    ['我', '的', '狗', '很', '可爱'],
    ['猫', '和', '狗', '都', '是', '宠物'],
    ['小猫', '喜欢', '抓', '老鼠', '小狗', '喜欢', '咬', '球'],
    ['兔子', '吃', '胡萝卜', '熊猫', '吃', '竹子'],
    ['蝴蝶', '在', '花', '丛', '中', '飞'],
    ['小鸟', '在', '天', '上', '飞'],
    # ---- 电脑 / 科技 ----
    ['我', '用', '电脑', '写', '程序'],
    ['电脑', '运行', '程序', '很', '快'],
    ['手机', '屏幕', '很', '大'],
    ['键盘', '和', '鼠标', '都', '是', '电脑', '配件'],
    ['数据', '存储', '在', '电脑', '硬盘', '里'],
    ['我', '用', '手机', '看', '视频'],
    # ---- 日常生活 ----
    ['今天', '天气', '很', '好'],
    ['我', '每天', '早上', '喝', '咖啡'],
    ['妈妈', '在', '厨房', '做', '饭'],
    ['爸爸', '在', '客厅', '看', '电视'],
]

MODE = "load"  # train/load

if MODE == "train":

    model = Word2Vec(
        sentences=TEST_SENTENCES,  # 已分词的句子序列
        vector_size=512,  # 词向量维度
        window=5,  # 上下文窗口大小
        min_count=1,  # 最小词频 (低于将被忽略), 如果全低于这个，则预料会被过滤，导致词表为空, 从而报错
        sg=1,  # 1: Skip-Gram  0: CBOW
        workers=4,  # 并行训练线程数
    )

    # 完整保存整个模型
    # model.save('word2vec.model')

    # 仅保存词向量 (wv类型为KeyedVectors)
    model.wv.save_word2vec_format("assets/gx_word_vectors.kv")

else:
    # 加载完整模型
    # model = Word2Vec.load('word2vec.model')

    # 仅仅加载词向量 (参考chapter02_02_word2vec.py的用法)
    vec = KeyedVectors.load_word2vec_format("assets/gx_word_vectors.kv")
    print(vec.vector_size)
    print(vec.similarity("葡萄", "橘子"))  # 0.007432889
    print(vec.similarity("宠物", "小猫"))  # -0.047155544 预料不行，没有太大意义.
    pass
