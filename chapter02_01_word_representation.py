# 2. 语义化词向量(Word2Vec)
# 通过对大规模预料的学习，为每个词生成一个具有语义意义的稠密向量表示, 这些向量
# 能够再连续空间中表达词和词之间的关系，使得意思相近的词在空间中距离更近.
# eg:
# 1) 女人和女孩的距离和男人和男孩的距离接近
# 2) 女人-女孩 ~ 男人-男孩


